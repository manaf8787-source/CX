import * as React from "react"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "cn"
import { Loader2Icon } from "lucide-react"
import { Slot } from "radix-ui"

/**
 * Pill button, Meo-inspired (docs/MEO_DESIGN_SYSTEM.md). Two materials: `default` is the dark primary pill (also `destructive` and `gold`:
 * a destructive action keeps the dark button and says its verb), `outline` and `secondary` are the light pill, `ghost` has no fill.
 * Sizes: sm 36 (toolbar), default 40, lg 46 (forms, cards). The asymmetric padding (top 4, bottom 6) centres Plus Jakarta Sans optically.
 */
const buttonVariants = cva(
  "inline-flex shrink-0 items-center justify-center rounded-full font-medium whitespace-nowrap select-none outline-none transition-[background-color,opacity,translate,box-shadow] duration-200 ease-out active:translate-y-px active:shadow-raised-dark disabled:cursor-not-allowed disabled:opacity-40 disabled:shadow-none data-[loading=true]:disabled:cursor-progress data-[loading=true]:disabled:opacity-100 aria-disabled:pointer-events-none aria-disabled:opacity-40 aria-disabled:shadow-none [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
  {
    variants: {
      variant: {
        default: "bg-grad-dark-button text-primary-foreground shadow-button-primary",
        destructive: "bg-grad-dark-button text-primary-foreground shadow-button-primary",
        gold: "bg-grad-dark-button text-primary-foreground shadow-button-primary",
        outline: "bg-grad-light text-foreground shadow-button-secondary active:shadow-raised-light",
        secondary: "bg-grad-light text-foreground shadow-button-secondary active:shadow-raised-light",
        ghost: "text-foreground hover:bg-(--hover-tint) active:shadow-none",
        link: "rounded-sm text-foreground underline-offset-4 hover:underline active:translate-y-0 active:shadow-none",
      },
      size: {
        default: "h-10 gap-[9px] px-[22px] pt-1 pb-1.5 text-lg",
        lg: "h-[46px] gap-[9px] px-[22px] pt-1 pb-1.5 text-lg",
        sm: "h-9 gap-1.5 px-3.5 pt-1 pb-1.5 text-sm [&_svg:not([class*='size-'])]:size-3.5",
        xs: "h-7 gap-1.5 px-3 pt-[3px] pb-[5px] text-xs [&_svg:not([class*='size-'])]:size-3.5",
        icon: "size-9 p-0",
        "icon-lg": "size-10 p-0",
        "icon-sm": "size-[30px] p-0 [&_svg:not([class*='size-'])]:size-3.5",
        "icon-xs": "size-[26px] p-0 [&_svg:not([class*='size-'])]:size-3",
      },
    },
    compoundVariants: [
      { variant: "ghost", size: ["default", "lg"], class: "px-3.5" },
      { variant: "link", size: ["default", "lg", "sm", "xs"], class: "h-auto p-0" },
      { variant: ["outline", "secondary", "ghost", "link"], size: ["icon", "icon-lg", "icon-sm", "icon-xs"], class: "p-0" },
    ],
    defaultVariants: {
      variant: "default",
      size: "default",
    },
  }
)

const ICON_SIZES = new Set(["icon", "icon-lg", "icon-sm", "icon-xs"])

/**
 * Hover label roll. Only for plain-text children: one text run, with at most childless elements (icons) around it. The copy that rolls
 * in is generated by CSS from `data-label` (theme.css), so the DOM keeps ONE label: the accessible name, getByText and screen readers
 * see it once. Returns null when the children are anything else (spans, components with children): no roll.
 */
function rollChildren(children: React.ReactNode): React.ReactNode[] | null {
  const items = React.Children.toArray(children)
  const isText = (n: React.ReactNode) => typeof n === "string" || typeof n === "number"
  const textAt = items.flatMap((n, i) => (isText(n) ? [i] : []))
  if (textAt.length === 0) return null
  const first = textAt[0]
  const last = textAt[textAt.length - 1]
  if (last - first + 1 !== textAt.length) return null
  const around = [...items.slice(0, first), ...items.slice(last + 1)]
  const iconLike = (n: React.ReactNode) =>
    React.isValidElement<{ children?: React.ReactNode }>(n) && (n.props.children === undefined || n.props.children === null)
  if (!around.every(iconLike)) return null
  const label = items.slice(first, last + 1).join("").trim()
  if (!label) return null
  return [
    ...items.slice(0, first),
    <span key="roll" className="btn-roll">
      <span className="btn-roll-inner" data-label={label}>
        {label}
      </span>
    </span>,
    ...items.slice(last + 1),
  ]
}

function Button({
  className,
  variant = "default",
  size = "default",
  asChild = false,
  loading = false,
  children,
  disabled,
  ...props
}: React.ComponentProps<"button"> &
  VariantProps<typeof buttonVariants> & {
    asChild?: boolean
    /** Shows a 14px spinner before the label, disables the button and sets aria-busy. */
    loading?: boolean
  }) {
  const Comp = asChild ? Slot.Root : "button"
  const rollable = !asChild && variant !== "link" && size !== "xs" && !ICON_SIZES.has(size ?? "")
  const rolled = rollable ? rollChildren(children) : null

  return (
    <Comp
      data-slot="button"
      data-variant={variant}
      data-size={size}
      className={cn(buttonVariants({ variant, size, className }), rolled && "btn-rollable")}
      disabled={asChild ? disabled : disabled || loading}
      aria-busy={loading || undefined}
      data-loading={loading || undefined}
      {...props}
    >
      {asChild ? (
        children
      ) : (
        <>
          {loading && <Loader2Icon aria-hidden className="size-3.5 animate-spin" />}
          {rolled ?? children}
        </>
      )}
    </Comp>
  )
}

export { Button, buttonVariants }
